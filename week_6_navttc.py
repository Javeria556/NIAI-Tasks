import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn import metrics

# 1. Dataset Direct URL (Pima Indians Diabetes Dataset)
url = "https://raw.githubusercontent.com/jbrownlee/Datasets/master/pima-indians-diabetes.data.csv"
col_names = ['pregnant', 'glucose', 'bp', 'skin', 'insulin', 'bmi', 'pedigree', 'age', 'label']

# Read dataset directly from the URL
pima = pd.read_csv(url, header=None, names=col_names)

print("--- Dataset Head ---")
print(pima.head())
print("\n" + "="*50 + "\n")

# 2. Feature Selection
feature_cols = ['pregnant', 'insulin', 'bmi', 'age', 'glucose', 'bp', 'pedigree']
X = pima[feature_cols]
y = pima['label']

# 3. Split Dataset (70% Train, 30% Test)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=1
)

# 4. Unpruned Decision Tree (Default - Gini Index)
clf_unpruned = DecisionTreeClassifier(random_state=1)
clf_unpruned = clf_unpruned.fit(X_train, y_train)
y_pred_unpruned = clf_unpruned.predict(X_test)
acc_unpruned = metrics.accuracy_score(y_test, y_pred_unpruned)

# 5. Optimized Decision Tree (Entropy & Pre-Pruning: max_depth=3)
clf_pruned = DecisionTreeClassifier(criterion="entropy", max_depth=3, random_state=1)
clf_pruned = clf_pruned.fit(X_train, y_train)
y_pred_pruned = clf_pruned.predict(X_test)
acc_pruned = metrics.accuracy_score(y_test, y_pred_pruned)

print(f"Unpruned Decision Tree Accuracy: {acc_unpruned * 100:.2f}%")
print(f"Optimized Decision Tree (Entropy, max_depth=3) Accuracy: {acc_pruned * 100:.2f}%\n")

print("--- Classification Report (Optimized Model) ---")
target_names = ['without diabetes', 'with diabetes']
print(metrics.classification_report(y_test, y_pred_pruned, target_names=target_names))

# 6. Visualization: Decision Tree Structure & Confusion Matrix
fig, axes = plt.subplots(1, 2, figsize=(16, 6))

# Plot Tree Structure
plot_tree(clf_pruned, feature_names=feature_cols, class_names=['0', '1'], filled=True, rounded=True, ax=axes[0])
axes[0].set_title('Optimized Decision Tree Structure (max_depth=3)', fontsize=12)

# Plot Confusion Matrix Heatmap
cm = metrics.confusion_matrix(y_test, y_pred_pruned)
sns.heatmap(pd.DataFrame(cm), annot=True, cmap="Blues", fmt='g', ax=axes[1],
            xticklabels=target_names, yticklabels=target_names)
axes[1].set_title(f'Confusion Matrix\nAccuracy: {acc_pruned * 100:.2f}%', fontsize=12)
axes[1].set_ylabel('Actual Label')
axes[1].set_xlabel('Predicted Label')

plt.tight_layout()
plt.show()

