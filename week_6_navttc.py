# 1. Download and Load Dataset directly from UCI Machine Learning Repository
data_link = "https://archive.ics.uci.edu/ml/machine-learning-databases/00267/data_banknote_authentication.txt"
col_names = ["variance", "skewness", "curtosis", "entropy", "class"]

# Read CSV directly from remote URL
bankdata = pd.read_csv(data_link, names=col_names, sep=",", header=None)

# Save local copy
bankdata.to_csv("banknote_authentication.csv", index=False)

print("--- First 5 Rows ---")
print(bankdata.head())

print("\n--- Dataset Shape ---")
print(bankdata.shape)

# 2. Divide Data into Features (X) and Target Label (y)
X = bankdata.drop('class', axis=1)
y = bankdata['class']

# 3. Train / Test Split (80% Train, 20% Test)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42
)

# 4. Model Training & Kernel Comparison
classifiers = {
    'Linear': SVC(kernel='linear', random_state=42),
    'Polynomial (Degree 8)': SVC(kernel='poly', degree=8, random_state=42),
    'Gaussian RBF': SVC(kernel='rbf', random_state=42),
    'Sigmoid': SVC(kernel='sigmoid', random_state=42)
}

# 5. Evaluate All SVM Kernels
fig, axes = plt.subplots(2, 2, figsize=(12, 10))
axes = axes.ravel()

for idx, (name, clf) in enumerate(classifiers.items()):
    # Fit model on training set
    clf.fit(X_train, y_train)

    # Make predictions on test set
    y_pred = clf.predict(X_test)

    acc = accuracy_score(y_test, y_pred)
    cm = confusion_matrix(y_test, y_pred)

    print(f"\n{'='*20} {name.upper()} KERNEL {'='*20}")
    print(f"Accuracy: {acc*100:.2f}%")
    print("\nConfusion Matrix:")
    print(cm)
    print("\nClassification Report:")
    print(classification_report(y_test, y_pred))

    # Plot heatmap
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=axes[idx], cbar=False)
    axes[idx].set_title(f'{name} Kernel\nAccuracy: {acc*100:.2f}%', fontsize=12)
    axes[idx].set_xlabel('Predicted Class')
    axes[idx].set_ylabel('Actual Class')

