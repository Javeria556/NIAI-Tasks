"""**Task 55(Time Series Analysis)**"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Dataset Direct URL (Open Power System Data for Germany)
url = "https://raw.githubusercontent.com/jenfly/opsd/master/opsd_germany_daily.csv"

# Load dataset directly from URL
opsd_daily = pd.read_csv(url)

# Save local copy
opsd_daily.to_csv("opsd_germany_daily.csv", index=False)

# 2. Time Series Setup: Convert Date to Datetime Index
opsd_daily['Date'] = pd.to_datetime(opsd_daily['Date'])
opsd_daily = opsd_daily.set_index('Date')

# Feature Engineering: Add Year, Month, and Weekday
opsd_daily['Year'] = opsd_daily.index.year
opsd_daily['Month'] = opsd_daily.index.month
opsd_daily['Weekday_Name'] = opsd_daily.index.day_name()

print("--- Dataset Head ---")
print(opsd_daily.head())

# 3. Time-based Selection and Slicing Examples
print("\n--- Slice for Single Year (2017) ---")
print(opsd_daily.loc['2017'].head(3))

print("\n--- Slice Date Range (2017-01-20 to 2017-01-22) ---")
print(opsd_daily.loc['2017-01-20':'2017-01-22'])

# 4. Visualization: Overall Production and Consumption Trends
fig, ax = plt.subplots(figsize=(12, 5))
opsd_daily[['Consumption', 'Solar', 'Wind']].plot(ax=ax, linewidth=0.6, alpha=0.8)
ax.set_ylabel('Daily Totals (GWh)')
ax.set_title('Germany Electricity Production & Consumption (2006–2017)', fontsize=13)
plt.tight_layout()
plt.show()

# 5. Seasonality Analysis using Boxplots
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Monthly Seasonality
sns.boxplot(data=opsd_daily, x='Month', y='Consumption', ax=axes[0], palette='Blues')
axes[0].set_title('Monthly Consumption Seasonality')
axes[0].set_ylabel('Consumption (GWh)')

# Weekly Seasonality
weekday_order = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']
sns.boxplot(data=opsd_daily, x='Weekday_Name', y='Consumption', ax=axes[1], palette='Greens', order=weekday_order)
axes[1].set_title('Weekly Consumption Seasonality')
axes[1].set_ylabel('Consumption (GWh)')

plt.tight_layout()
plt.show()

# 6. Resampling & Rolling Windows Analysis
opsd_7d = opsd_daily[['Consumption', 'Solar', 'Wind']].rolling(7, center=True).mean()
opsd_365d = opsd_daily[['Consumption', 'Solar', 'Wind']].rolling(365, center=True).mean()

fig, ax = plt.subplots(figsize=(12, 5))
ax.plot(opsd_daily['Consumption'], marker='.', markersize=2, color='0.7', linestyle='None', alpha=0.5, label='Daily')
ax.plot(opsd_7d['Consumption'], color='tab:blue', linewidth=1.5, label='7-Day Rolling Mean')
ax.plot(opsd_365d['Consumption'], color='tab:red', linewidth=2, label='365-Day Rolling Mean')

ax.set_ylabel('Consumption (GWh)')
ax.set_title('Electricity Consumption Trends (Rolling Means)', fontsize=13)
ax.legend(loc='upper left')
plt.tight_layout()
plt.show()