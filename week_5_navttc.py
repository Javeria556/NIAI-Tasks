import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score

# 1. Load Built-In Digits Dataset
digits = load_digits()

print(f"Data Shape: {digits.data.shape}")  # (1797, 64) -> 8x8 pixel images flattened
print(f"Target Shape: {digits.target.shape}")
print("\n" + "="*50 + "\n")

# 2. Train / Test Split
X_train, X_test, y_train, y_test = train_test_split(
    digits.data, digits.target, test_size=0.25, random_state=42
)

# 3. Fit Multi-Class Model
# L-BFGS solver handles multinomial loss directly
logisticRegr = LogisticRegression(solver='lbfgs', max_iter=10000, random_state=42)
logisticRegr.fit(X_train, y_train)

# 4. Predict & Evaluate Accuracy
predictions = logisticRegr.predict(X_test)
score = accuracy_score(y_test, predictions)

print(f"Overall Accuracy: {score * 100:.2f}%\n")

# 5. Detailed Classification Metrics
print("--- Multi-Class Classification Report ---")
print(classification_report(y_test, predictions))

# 6. Visualization: Sample Image & Confusion Matrix Heatmap
fig, axes = plt.subplots(1, 2, figsize=(14, 6))

# Plot 1: Sample Digit Prediction Visualization
sample_img = X_test[0].reshape(8, 8)
sample_pred = predictions[0]
sample_true = y_test[0]

axes[0].imshow(sample_img, cmap=plt.cm.gray)
axes[0].set_title(f"Sample Test Digit\nTrue: {sample_true} | Predicted: {sample_pred}", fontsize=12)
axes[0].axis('off')

# Plot 2: Multi-Class Confusion Matrix Heatmap
cm = confusion_matrix(y_test, predictions)
sns.heatmap(cm, annot=True, fmt="d", linewidths=.5, square=True, cmap='Blues', ax=axes[1])
axes[1].set_ylabel('Actual Label')
axes[1].set_xlabel('Predicted Label')
axes[1].set_title(f'MNIST Digits Confusion Matrix\nAccuracy Score: {score * 100:.2f}%', fontsize=12)

plt.tight_layout()
plt.show()